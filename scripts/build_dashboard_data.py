"""
Aggregate the CSVs into the compact JSON the web dashboard needs and inject it into
docs/index.html (between the DATA markers), so the dashboard works on GitHub Pages
and when opened straight from disk.

Run:  python scripts/build_dashboard_data.py
"""
from pathlib import Path
import json
import re
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "data"

sup = pd.read_csv(D / "dim_supplier.csv")
prod = pd.read_csv(D / "dim_product.csv")
loc = pd.read_csv(D / "dim_location.csv")
po = pd.read_csv(D / "fact_po_line.csv", parse_dates=["order_date", "promised_date", "received_date"])
inv = pd.read_csv(D / "fact_inventory_daily.csv")
inv["date"] = pd.to_datetime(inv.date_key.astype(str))
inv["month"] = inv.date.dt.month

sup_i = {s: i for i, s in enumerate(sup.supplier_id)}
sku_i = {s: i for i, s in enumerate(prod.sku)}
loc_i = {s: i for i, s in enumerate(loc.location_id)}

# ---- PO lines (received only; open lines are excluded from OTIF by definition)
r = po[po.received_date.notna()].copy()
po_rows = [[
    sup_i[x.supplier_id], sku_i[x.sku], loc_i[x.location_id],
    int(x.promised_date.month),
    int((x.received_date - x.promised_date).days),     # days late (negative = early)
    int(x.qty_ordered), int(x.qty_received), round(float(x.line_value_gbp), 2),
    x.po_number, x.order_date.strftime("%d %b"), x.promised_date.strftime("%d %b"), x.received_date.strftime("%d %b"),
] for x in r.itertuples()]

# ---- inventory: per SKU x location x month
pc = prod.set_index("sku")
g = inv.groupby(["sku", "location_id", "month"])
agg = g.agg(days=("closing_stock", "size"),
            stockout_days=("closing_stock", lambda s: int((s == 0).sum())),
            lost=("lost_sales_units", "sum")).reset_index()
month_end = inv.loc[inv.groupby(["sku", "location_id", "month"]).date.idxmax(),
                    ["sku", "location_id", "month", "date", "closing_stock", "forecast_daily_demand"]]
agg = agg.merge(month_end, on=["sku", "location_id", "month"])


def on_order(row):
    m = po[(po.sku == row.sku) & (po.location_id == row.location_id) & (po.order_date <= row.date) &
           (po.received_date.isna() | (po.received_date > row.date))]
    return int(m.qty_ordered.sum())


agg["on_order"] = agg.apply(on_order, axis=1)
inv_rows = [[
    sku_i[x.sku], loc_i[x.location_id], int(x.month), int(x.days), int(x.stockout_days), int(x.lost),
    int(x.closing_stock), round(float(x.forecast_daily_demand), 2), int(x.on_order),
] for x in agg.itertuples()]

data = {
    "note": "Synthetic data generated by scripts/generate_data.py",
    "suppliers": sup[["supplier_id", "supplier_name", "category", "promised_lead_time_days"]].values.tolist(),
    "products": prod[["sku", "product_name", "category", "supplier_id", "unit_cost_gbp", "abc_class",
                      "min_cover_days", "max_cover_days"]].values.tolist(),
    "locations": loc[["location_id", "location_name"]].values.tolist(),
    "po": po_rows,
    "inv": inv_rows,
}
payload = json.dumps(data, separators=(",", ":"))
html_path = ROOT / "docs" / "index.html"
html = html_path.read_text()
html = re.sub(r"/\*DATA_START\*/.*?/\*DATA_END\*/",
              lambda _: f"/*DATA_START*/{payload}/*DATA_END*/", html, flags=re.S)
html_path.write_text(html)
print(f"injected {len(payload)/1024:.0f} KB: {len(po_rows):,} PO lines, {len(inv_rows):,} inventory rows")
